"""The canonical-file matrix — what an instant must contain, indexed on THREE axes.

`(state, opType, spec-version)`. Not two. The `spec-version` axis has now been dropped from a
specification twice, so this module names every cell explicitly rather than deriving them: a dropped
row is then a visible deletion instead of a silently absent branch (FR2-2.2).

Why the matrix is data and not a chain of `if`s: `W2-21` demanded `COMPACTED.md` of every `-compact-`
instant, which makes a correctly-running compaction lint RED for its entire life — an alarm that cannot
be cleared by doing the right thing. Its fix reached `inflight` and `complete` and never `abort`, because
the states were branches in code rather than rows in a table. Here `abort` is a row, and a row is hard to
forget.

Why `STATE.md` is `FORBIDDEN` in every cell and the bootstrap cannot create one: four consumers
disagreed about that file — the bootstrap seeded it, the format checklist forbade it, the folding skill
folded it and the review skill auto-fixed it away — so a worker that followed the template it was given
failed the gate it was held to (`RCF-11`/FD-7). One fact, one home.

Why an earlier spec version downgrades rather than fails: `OBS-9` stated that a fix changing how state is
INTERPRETED needs a migration path for state that already exists, and the very next field shipped four
hours later without one (`W2-5`). Greenfield removes today's legacy; it does not remove the *next* layout
change.

This module is one of the two presence-only exemptions to "no module reads a `.md` file" (AC-2): it asks
whether a file exists and never what it says. Nothing here opens a markdown file for a control signal.
"""
from dataclasses import dataclass
from pathlib import Path

from fleet.errors import BadInput
from fleet.identity import InstantName

REQUIRED, DUE_LATER, OPTIONAL, FORBIDDEN = "required", "due-later", "optional", "forbidden"
REQUIREMENTS_DOMAIN = (REQUIRED, DUE_LATER, OPTIONAL, FORBIDDEN)

SPEC_VERSION = 1

VIOLATION, INFO = "violation", "info"

#: The six documents every instant carries in every state, in reading order.
CANONICAL = ("HANDOFF.md", "CHARTER.md", "RUNBOOK.md", "DECISIONS.md", "ISSUES.md", "ASSUMPTIONS.md")

#: Directories, distinguished from files by a trailing slash in the matrix key.
CANONICAL_DIRS = ("evidence/", "investigations/", "plans/")

_INDEX = "evidence/INDEX.md"


@dataclass(frozen=True)
class Violation:
    """One finding. `severity` is the whole point of the `DUE_LATER` cell: a document that is not due
    yet is reported as `info`, so a running compaction is never RED for being mid-flight."""

    path: str
    rule: str
    detail: str
    severity: str


def _always() -> dict:
    """The part of a cell that does not vary. Spelled once; the varying part is spelled per cell."""
    row = {name: REQUIRED for name in CANONICAL}
    row[_INDEX] = REQUIRED
    for directory in CANONICAL_DIRS:
        row[directory] = REQUIRED
    row["STATE.md"] = FORBIDDEN          # FD-7 — in every cell, with no exception
    row["REVIEW.md"] = OPTIONAL          # generated by `review`, never hand-written
    return row


#: The matrix. One dict keyed `(state, opType)` -> `{filename: requirement}`. Six cells, all six named.
REQUIREMENTS = {
    ("inflight", "append"): {**_always(), "COMPACTED.md": FORBIDDEN},
    ("complete", "append"): {**_always(), "COMPACTED.md": FORBIDDEN},
    ("abort", "append"): {**_always(), "COMPACTED.md": FORBIDDEN},
    ("inflight", "compact"): {**_always(), "COMPACTED.md": DUE_LATER},
    ("complete", "compact"): {**_always(), "COMPACTED.md": REQUIRED},
    ("abort", "compact"): {**_always(), "COMPACTED.md": OPTIONAL},
}

_TEMPLATES = {
    "HANDOFF.md": "Entry point. Current state first, then the pickup guide.\n",
    "CHARTER.md": "Durable. Goal, the first three raw prompts verbatim, ACs as NL -> proof -> self-review.\n",
    "RUNBOOK.md": "Runnable commands only. No prose instructions.\n",
    "DECISIONS.md": "Append-only. One section per decision, each naming its tie-breaker.\n",
    "ISSUES.md": "Append-only. One sub-section per issue, each with an id.\n",
    "ASSUMPTIONS.md": "One line per assumption: OPEN / VERIFIED / REFUTED / SANCTIONED / DEFERRED.\n",
    _INDEX: "criterion -> artifact -> source -> how to regenerate.\n",
}


def requirement(state: str, optype: str, filename: str,
                spec_version: int = SPEC_VERSION) -> str:
    """The requirement for one file in one cell, at one spec version.

    A `(state, opType)` pair outside the matrix is refused rather than defaulted: a missing row must not
    read as "nothing is required here", which is exactly how a dropped axis survives (FD-1, no legacy
    tolerance). A filename the matrix does not mention is `OPTIONAL` — the matrix constrains the
    canonical set, it does not forbid an instant's own working files.
    """
    if spec_version > SPEC_VERSION:
        raise BadInput(
            f"spec_version={spec_version!r} is newer than this build knows ({SPEC_VERSION}); "
            "refusing to interpret a layout spec from the future."
        )
    try:
        cell = REQUIREMENTS[(state, optype)]
    except KeyError:
        raise BadInput(
            f"({state!r}, {optype!r}) is not a cell of the layout matrix. Cells: "
            + ", ".join(f"({s}, {o})" for s, o in sorted(REQUIREMENTS))
        ) from None
    verdict = cell.get(filename, OPTIONAL)
    if spec_version < SPEC_VERSION and verdict in (REQUIRED, DUE_LATER):
        # An artifact created under an earlier spec version renders info:, never a violation.
        return OPTIONAL
    return verdict


def bootstrap(instant: Path, name: InstantName) -> list:
    """Create exactly what the matrix requires of this cell. Returns what it created.

    Idempotent and non-clobbering: a second call over a populated instant creates nothing and returns an
    empty list, because a bootstrap that overwrites a worker's own CHARTER is a bootstrap nobody can run
    twice. A `FORBIDDEN` file is never created — the seed and the gate read the same table, so the
    `RCF-11` disagreement has no place to live.
    """
    instant = Path(instant)
    cell = REQUIREMENTS.get((name.state, name.optype))
    if cell is None:
        raise BadInput(f"({name.state!r}, {name.optype!r}) is not a cell of the layout matrix")
    created = []
    instant.mkdir(parents=True, exist_ok=True)
    for entry in sorted(cell, key=lambda e: (not e.endswith("/"), e)):
        if requirement(name.state, name.optype, entry) != REQUIRED:
            continue
        target = instant / entry.rstrip("/")
        if entry.endswith("/"):
            if not target.is_dir():
                target.mkdir(parents=True, exist_ok=True)
                created.append(target)
            continue
        if target.exists():
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(_seed(entry, name))
        created.append(target)
    return created


def seed_headings(entry: str, name: InstantName) -> tuple:
    """Every markdown heading `_seed` writes into `entry`, heading text only, in file order.

    Declared here, next to the seed and read BY the seed, because a consumer that needs to recognise a
    seeded-but-unwritten document has to compare against the seed's real shape rather than against a
    second copy of it. `FI-18` is what the second copy costs: `harvest`'s vacuity guard read the seed's
    own header as a register whose extractor had gone blind, and a brand-new effort was a violation on
    every tick — the fifth instance of the unclearable-alarm family, and this build's own.

    Recognition is on the heading TEXT and nothing else. The body is prose a worker is expected to
    replace line by line, so making the whole document the identity would stop recognising a register the
    moment somebody edited its `Updated:` line.
    """
    title = entry.rsplit("/", 1)[-1]
    if title.endswith(".md"):
        title = title[: -len(".md")]
    return (f"{title} — {name.name}",)


def _seed(entry: str, name: InstantName) -> str:
    """A minimal document carrying the two header fields every consumer of these files reads."""
    return (
        "".join(f"# {heading}\n" for heading in seed_headings(entry, name))
        + f"\nUpdated: {name.curr}\n"
        f"Status: seeded by fleet.layout (spec-version {SPEC_VERSION})\n\n"
        f"{_TEMPLATES.get(entry, '')}"
    )


def validate(instant: Path, spec_version: int = SPEC_VERSION) -> list:
    """Check one instant against its cell. Presence only — never content.

    The folder name is parsed through `identity` FIRST, so a non-conforming folder is refused rather than
    judged (FD-1/FD-2): silently treating a folder that is not an instant as one is how legacy tolerance
    re-enters through the checker.

    The last row is always a `population` row naming what was examined. A check whose scope narrows
    silently reads as a pass (`OBS-49`), so the scope is part of the output rather than part of the
    reader's assumptions.
    """
    instant = Path(instant)
    name = InstantName.parse(instant.name)      # raises InstantNameError — refused, not judged
    if not instant.is_dir():
        raise BadInput(f"{instant} is not a directory; there is nothing to validate")

    cell = REQUIREMENTS.get((name.state, name.optype))
    if cell is None:
        raise BadInput(f"({name.state!r}, {name.optype!r}) is not a cell of the layout matrix")

    out = []
    files_checked = dirs_checked = 0
    for entry in sorted(cell):
        is_dir = entry.endswith("/")
        target = instant / entry.rstrip("/")
        present = target.is_dir() if is_dir else target.is_file()
        if is_dir:
            dirs_checked += 1
        else:
            files_checked += 1
        verdict = requirement(name.state, name.optype, entry, spec_version)
        if verdict == REQUIRED and not present:
            out.append(Violation(
                path=str(target), rule="required",
                detail=f"{entry} is required for ({name.state}, {name.optype}) and is missing",
                severity=VIOLATION))
        elif verdict == DUE_LATER and not present:
            out.append(Violation(
                path=str(target), rule="due-later",
                detail=(f"{entry} is not due yet for ({name.state}, {name.optype}); it is due at "
                        "-complete-. This is information, not a fault."),
                severity=INFO))
        elif verdict == FORBIDDEN and present:
            out.append(Violation(
                path=str(target), rule="forbidden",
                detail=(f"{entry} is forbidden in every cell of the matrix; delete it. One fact, one "
                        "home (FD-7)."),
                severity=VIOLATION))

    on_disk = len(list(instant.iterdir()))
    out.append(Violation(
        path=str(instant), rule="population",
        detail=(f"examined {files_checked} file rules and {dirs_checked} dir rules from cell "
                f"({name.state}, {name.optype}) at spec-version {spec_version}; "
                f"{on_disk} entries present in the folder"),
        severity=INFO))
    return out
